"""Download the Google Fonts each page uses into vendor/fonts and rewrite the pages to use them.
Usage: python -I bundle_fonts.py <project_dir>
Keeps only the latin + latin-ext subsets (enough for the romanised names used at the event)."""
import hashlib, os, re, sys, urllib.request

proj = sys.argv[1]
out_dir = os.path.join(proj, 'vendor', 'fonts'); files_dir = os.path.join(out_dir, 'files')
os.makedirs(files_dir, exist_ok=True)
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'  # gets woff2
KEEP = {'latin', 'latin-ext'}

def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()

pages = [os.path.join(proj, 'index.html')] + sorted(
    os.path.join(proj, 'designs', f) for f in os.listdir(os.path.join(proj, 'designs')) if f.endswith('.html'))
downloaded = {}
total = 0
for page in pages:
    html = open(page, encoding='utf-8').read()
    m = re.search(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com/css2\?[^"]+)">', html)
    if not m:
        print('skip (no google font link):', page); continue
    url = m.group(1).replace('&amp;', '&')
    css = get(url).decode('utf-8')
    # split into /* subset */ @font-face {...} blocks
    blocks = re.findall(r'/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})', css)
    kept = []
    for subset, block in blocks:
        if subset not in KEEP: continue
        src = re.search(r'url\((https://fonts\.gstatic\.com/[^)]+)\)', block).group(1)
        if src not in downloaded:
            data = get(src)
            fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
            name = f"{fam.replace(' ', '')}-{hashlib.sha1(src.encode()).hexdigest()[:10]}.woff2"
            with open(os.path.join(files_dir, name), 'wb') as f: f.write(data)
            downloaded[src] = name; total += len(data)
        kept.append(f'/* {subset} */\n' + block.replace(src, 'files/' + downloaded[src]))
    base = 'hub' if os.path.basename(page) == 'index.html' else os.path.splitext(os.path.basename(page))[0]
    with open(os.path.join(out_dir, base + '.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'/* Local copy of {url}\n   (latin + latin-ext subsets only). Generated by bundle_fonts.py. */\n' + '\n'.join(kept) + '\n')
    rel = 'vendor/fonts/' if base == 'hub' else '../vendor/fonts/'
    html = html.replace(m.group(0), f'<link rel="stylesheet" href="{rel}{base}.css">')
    html = re.sub(r'<link rel="preconnect" href="https://fonts\.googleapis\.com">\r?\n', '', html)
    with open(page, 'w', encoding='utf-8', newline='') as f: f.write(html)
    print(f'{os.path.basename(page):16} -> {base}.css  ({len(kept)} faces)')
print(f'{len(downloaded)} font files, {total/1024:.0f} KB')
